// Polestar's maps on the engine, on routes where Shortest Path Forever's own maps cut the Razor Hill inn's
// wall and swim to Teldrassil (docs/ARCHITECTURE.md, "Packing for the in-game engine").
const ENGINE = `
local Path = Polestar_NavEngine
local function d(ax, ay, bx, by) return math.sqrt((ax - bx) ^ 2 + (ay - by) ^ 2) end
-- Nearest approach of a polyline to (x, y) within its first \`upto\` yards.
local function near(p, x, y, upto)
	local best, walked = math.huge, 0
	for i = 2, #p do
		local a, b = p[i - 1], p[i]
		local L = d(a.x, a.y, b.x, b.y)
		for s = 0, 20 do
			local t = s / 20
			if walked + t * L <= upto then best = math.min(best, d(a.x + (b.x - a.x) * t, a.y + (b.y - a.y) * t, x, y)) end
		end
		walked = walked + L
	end
	return best
end
local r = {}
-- Razor Hill's inn (Innkeeper Grosk) to the Valley of Strength.
local inn = Path.FindSync(1, { x = 340.523, y = -4686.091, z = 16.458 }, { x = 1633.959, y = -4439.410, z = 15.480 })
r.door = inn and near(inn, 333.7, -4700.3, 30)
-- The Ruins of Lordaeron's courtyard to the Trade Quarter: to an Undervator's top landing, from its bottom one.
local _, top = Path.FindSync(0, { x = 1713.688, y = 231.708, z = 62.598 }, { x = 1596.150, y = 291.800, z = 55.718 })
local _, bottom = Path.FindSync(0, { x = 1596.150, y = 291.800, z = -40.784 }, { x = 1567.110, y = 266.388, z = -59.285 })
local _, walk = Path.FindSync(0, { x = 1713.688, y = 231.708, z = 62.598 }, { x = 1567.110, y = 266.388, z = -59.285 })
r.lift = { top = top, bottom = bottom, walk = walk }
-- Auberdine (Darkshore) to Rut'theran Village (Teldrassil): open sea between.
local sea, why = Path.FindSync(1, { x = 6398.9, y = 531.267, z = 8.663 }, { x = 8797.237, y = 968.342, z = 30.265 })
r.sea = { found = sea ~= nil, why = why }
-- Ratchet to the Merchant Coast: a swim along it is still taken.
local coast, cost = Path.FindSync(1, { x = -846.775, y = -3720.55, z = 20.524 }, { x = -1502.131, y = -4024.55, z = 0 })
r.coast = { found = coast ~= nil, cost = cost }
emit(r)`;

test('Polestar\'s maps on the engine: the Razor Hill inn is left by its door, the Undercity reached by an Undervator, open sea never swum, a coast still is (NAV_QA themes: wall cuts; open sea)', () => {
	const [got] = runAddon({ stubs: ['stub_encoding.lua'], addons: ['Polestar_Nav'], script: ENGINE }).emitted;
	assert.ok(got.door < 3, `the walk out of the inn passes ${got.door?.toFixed(1)} yd from the door, not through the wall`);
	const { top, bottom, walk } = got.lift;
	assert.ok(top > 0 && bottom > 0, 'both Undervator landings are reached on foot (floor entrances: SpfUpstream\'s Path.lua:185 case)');
	// A ride: 3.5 s up or down plus 8.3 s of wait at most (Nav/TravelData.lua's Undervator), costs in running yards at 7 yd/s.
	assert.ok((top + bottom) / 7 + 12 < walk / 7, `by the lift ${((top + bottom) / 7 + 12).toFixed(0)} s, walking round ${(walk / 7).toFixed(0)} s`);
	assert.deepEqual(got.sea, { found: false, why: 'unreachable' }, 'fatigue water is no surface: no swim to Teldrassil');
	assert.ok(got.coast.found && got.coast.cost > 0, 'the walk along the Merchant Coast still routes');
});

