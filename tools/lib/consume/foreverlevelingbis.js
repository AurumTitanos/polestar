'use strict';
// ForeverLevelingBiS by Thunder (MIT): Forever's leveling gear and where it
// comes from. Reads the installed addon's generated data files (Data/Tables,
// Data/Items, Data/Quests, Data/Overrides) and its racial table (Racials.lua),
// all plain data. Facts only: ids, names, levels, stats, sources, rewards.
//
//   const { readForeverLevelingBiS } = require('./foreverlevelingbis');
//   const flb = readForeverLevelingBiS();            // the installed copy
//   flb.items[60].sources -> [{ type: 'quest', id: 6, name, zoneId, level, reqLevel, side }]
//
// Shapes kept as the addon writes them (Lookup reads `items[id].sources`):
//   quest  { type: 'quest', id, name, zoneId, level, reqLevel, side? (1 Alliance, 2 Horde, 3 both) }
//   drop   { type: 'drop', npcId?, npc, zoneId, zone, pct }
//   craft  { type: 'crafted', spellId, profession, skill }
// Each item also carries `polestar`: its stats in Polestar.Gear's keys
// (addon/Polestar/Gear/Weights.lua STAT_KEYS), weapon damage folded into
// `dps` (melee) or `rdps` (ranged), so the generator never re-maps.

const fs = require('node:fs');
const path = require('node:path');
const { resolveAddonsDir } = require('../addons');
const { addonVersion, readAddonLua, pairsToObject } = require('./lua');

const ADDON = 'ForeverLevelingBiS';
const FILES = ['Data/Tables.lua', 'Data/Items.lua', 'Data/Quests.lua', 'Data/Overrides.lua', 'Racials.lua'];

// Wowhead stat keys (as the addon stores them) -> Polestar stat keys. A
// "spell power" item (splpwr) raises damage and healing alike; spldmg is
// damage only and splheal healing only. Resistances are not scored.
const STAT_MAP = {
	str: ['str'], agi: ['agi'], sta: ['sta'], int: ['int'], spi: ['spi'],
	armor: ['armor'], armorbonus: ['armor'], health: ['health'], mana: ['mana'],
	atkpwr: ['ap'], rgdatkpwr: ['rap'],
	splpwr: ['sp', 'heal'], spldmg: ['sp'], splheal: ['heal'],
	arcsplpwr: ['spArcane'], firsplpwr: ['spFire'], frosplpwr: ['spFrost'], holsplpwr: ['spHoly'],
	natsplpwr: ['spNature'], shasplpwr: ['spShadow'],
	manargn: ['mp5'], healthrgn: ['hp5'],
	defrtng: ['defense'], dodgertng: ['dodge'], parryrtng: ['parry'], blockrtng: ['block'], block: ['blockValue'],
	hitrtng: ['hit'], critstrkrtng: ['crit'],
};
// Not scored by Polestar (recorded in meta.unmapped with counts when met).
const IGNORED = new Set(['arcres', 'firres', 'frores', 'natres', 'shares', 'holres', 'feratkpwr']);

// Inventory types of ranged weapons (bow/gun/crossbow, thrown, wand): their
// DPS is `rdps`.
const RANGED_INV = new Set([15, 25, 26]);

function polestarStats(item, unmapped) {
	const out = {};
	for (const [k, v] of Object.entries(item.stats || {})) {
		if (typeof v !== 'number' || v === 0) continue;
		const keys = STAT_MAP[k];
		if (!keys) {
			unmapped[k] = (unmapped[k] || 0) + 1;
			continue;
		}
		for (const key of keys) out[key] = (out[key] || 0) + v;
	}
	const w = item.weapon;
	if (w && typeof w.dps === 'number' && w.dps > 0) out[RANGED_INV.has(item.slot) ? 'rdps' : 'dps'] = Math.round(w.dps * 10) / 10;
	return out;
}

// Lua: every id-keyed table as sorted pairs (an id table that happens to
// start at 1 must not become an array); records as they are.
const EXPR = `local ns = POLESTAR_NS
return {
  info = ns.DataInfo,
  items = POLESTAR_pairs(ns.Items),
  overrides = POLESTAR_pairs(ns.Overrides),
  quests = POLESTAR_pairs(ns.Quests),
  chains = POLESTAR_pairs(ns.QuestChains),
  factions = POLESTAR_pairs(ns.FactionNames),
  zones = POLESTAR_pairs(ns.ZoneNames),
  races = ns.Races,
  racials = POLESTAR_pairs(ns.Racials),
  weaponProf = POLESTAR_pairs(ns.WeaponProficiencies),
  armorProf = POLESTAR_pairs(ns.ArmorProficiencies),
  dungeons = ns.Dungeons,
  patterns = ns.Patterns,
}`;

function stampOf(file) {
	const head = fs.readFileSync(file, 'utf8').slice(0, 400);
	const m = head.match(/GENERATED by (\S+) on (\d{4}-\d{2}-\d{2})/);
	return m ? { generator: m[1], generated: m[2] } : {};
}

// Apply Data/Overrides.lua as the addon does: false hides an item, a table
// replaces the listed fields (a new id adds a whole record).
function applyOverrides(items, overrides) {
	for (const [id, ov] of Object.entries(overrides)) {
		if (ov === false) delete items[id];
		else if (ov && typeof ov === 'object') items[id] = { ...(items[id] || {}), ...ov };
	}
}

// -> { meta, items, quests, chains, zones, factions, races, racials,
//      proficiency: { weapon, armor }, dungeons, patterns }
// `dir`: the addon folder (default: the installed copy under resolveAddonsDir).
function readForeverLevelingBiS({ dir, addons } = {}) {
	const root = dir || path.join(resolveAddonsDir(addons) || '', ADDON);
	if (!fs.existsSync(path.join(root, 'Data', 'Items.lua'))) {
		throw new Error(`${ADDON} not found at ${root} (install it, or pass dir / set WOW_FOREVER_ADDONS)`);
	}
	const files = FILES.map((f) => path.join(root, f)).filter((f) => fs.existsSync(f));
	const raw = readAddonLua({ files, addonName: ADDON, expr: EXPR });

	const items = {};
	for (const [id, rec] of raw.items) items[id] = rec;
	applyOverrides(items, pairsToObject(raw.overrides));

	const unmapped = {};
	for (const [id, rec] of Object.entries(items)) {
		rec.id = Number(id);
		rec.sources = Array.isArray(rec.sources) ? rec.sources : [];
		rec.polestar = polestarStats(rec, unmapped);
	}

	const quests = {};
	for (const [id, q] of raw.quests) {
		q.id = Number(id);
		quests[id] = q;
	}

	const licence = fs.existsSync(path.join(root, 'LICENSE')) ? fs.readFileSync(path.join(root, 'LICENSE'), 'utf8').split('\n')[0].trim() : null;
	const meta = {
		source: ADDON,
		author: 'Thunder',
		url: 'https://www.curseforge.com/wow/addons/forever-leveling-bis',
		licence: licence || 'MIT (X-License in the TOC)',
		version: addonVersion(root),
		...stampOf(path.join(root, 'Data', 'Items.lua')),
		files: files.map((f) => path.relative(root, f).replace(/\\/g, '/')),
		counts: {
			items: Object.keys(items).length,
			quests: Object.keys(quests).length,
			dungeons: (raw.dungeons || []).length,
			patterns: (raw.patterns || []).reduce((n, p) => n + ((p.patterns || []).length), 0),
			races: (raw.races || []).length,
		},
		unmapped,
	};

	// Races: facts only (id, name, faction, classes); trait descriptions are
	// the game's text and stay behind.
	const races = (raw.races || []).map((r) => ({
		id: r.id,
		name: r.name,
		faction: r.faction,
		classes: r.classes || [],
		traits: (r.traits || []).map((t) => ({ id: t.id, name: t.name })),
	}));

	const proficiency = { weapon: pairsToObject(raw.weaponProf), armor: pairsToObject(raw.armorProf) };

	return {
		meta,
		items,
		quests,
		chains: pairsToObject(raw.chains),
		zones: pairsToObject(raw.zones),
		factions: pairsToObject(raw.factions),
		races,
		racials: pairsToObject(raw.racials),
		proficiency,
		dungeons: raw.dungeons || [],
		patterns: raw.patterns || [],
	};
}

module.exports = { readForeverLevelingBiS, polestarStats, STAT_MAP, ADDON };
