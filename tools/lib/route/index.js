'use strict';
// First-draft leveling routes: reference data -> `.guide` text.
//
//   const { draft, loadData } = require('./lib/route');
//   const { text, report } = draft(loadData('data/forever'), {
//     faction: 'Alliance', race: 'Human', zones: ['Elwynn Forest'], levels: [1, 10] });
//
// model.js picks the candidate quests, planner.js simulates the route,
// emit.js writes the guide. Same inputs, same bytes.

const { loadData, buildModel, resolveZone, raceInfo, className } = require('./model');
const { planRoute } = require('./planner');
const { emitGuide } = require('./emit');

function slug(s) {
	return String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

// opts: { faction, race, class?, zones: [name|id], levels: [min, max], startQuest?,
//         start?: [x, y], id?, title?, next?, done?: [ids], trainers?: [[Class, npcId]],
//         keepBreadcrumbs? }
function draft(data, opts) {
	const warnings = [];
	const warn = (m) => warnings.push(m);
	const faction = { alliance: 'Alliance', horde: 'Horde' }[String(opts.faction || '').toLowerCase()];
	if (!faction) throw new Error('faction must be Alliance or Horde');
	if (!opts.race) throw new Error('race is required');
	const race = raceInfo(opts.race);
	if (race.faction && race.faction !== faction) throw new Error(`${race.name} is not a ${faction} race`);
	race.bit = race.bits[faction] || 0;
	if (!race.bit && Object.keys(race.bits).length) throw new Error(`${race.name} is not a ${faction} race`);
	if (!race.bit) warn(`race ${race.name} has no known bit: race-restricted quests are kept only when open to every ${faction} race (pass --race ${race.name}:<bit>)`);
	const cls = opts.class ? className(opts.class) : null;
	if (opts.class && !cls) throw new Error(`unknown class "${opts.class}"`);
	const [levelMin, levelMax] = opts.levels || [];
	if (!(levelMin >= 1 && levelMax >= levelMin && levelMax <= 60)) throw new Error('levels must be <min>-<max> within 1-60');
	if (!opts.zones || !opts.zones.length) throw new Error('at least one zone is required');
	const zones = opts.zones.map((z) => resolveZone(data.zones || {}, z));
	const trainers = (opts.trainers || []).map(([c, id]) => {
		const name = className(c);
		if (!name) throw new Error(`unknown class "${c}" in trainer`);
		return [name, Number(id)];
	});

	const mopts = {
		faction, race, class: cls, zones, levelMin, levelMax, trainers,
		done: (opts.done || []).map(Number),
	};
	const model = buildModel(data, mopts, warn);
	if (!opts.keepBreadcrumbs) model.breadcrumbs = [];
	let startPoint = null;
	if (opts.start) startPoint = model.project.point(zones[0].id, opts.start[0], opts.start[1]);
	const plan = planRoute(model, { ...mopts, startQuest: opts.startQuest != null ? Number(opts.startQuest) : null, startPoint });

	const zoneLabel = zones.map((z) => z.name || `map ${z.id}`).join(' & ');
	const final = plan.final.level + (plan.final.need ? plan.final.xp / plan.final.need : 0);
	const reasons = new Map();
	for (const e of model.excluded) reasons.set(e.reason.replace(/\d+(\/\d+)*/g, 'N'), (reasons.get(e.reason.replace(/\d+(\/\d+)*/g, 'N')) || 0) + 1);
	const comments = [
		'Draft generated by `polestar draft`: review every step in game before publishing.',
		`Routed ${plan.routed.length} quests; estimated level at the end ${final.toFixed(1)} (heuristic XP${cls ? '' : ', class quests not counted'}).`,
	];
	if (reasons.size) comments.push(`Skipped: ${[...reasons].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).map(([r, n]) => `${n} ${r}`).join('; ')}.`);
	const text = emitGuide(plan, {
		id: opts.id || `forever/${faction.toLowerCase()}/${slug(race.name)}/${slug(zoneLabel)}-${levelMin}-${levelMax}`,
		title: opts.title || `${zoneLabel} ${levelMin}-${levelMax}`,
		faction,
		race: race.name,
		class: cls,
		levelMin,
		levelMax,
		zones,
		next: opts.next || null,
		comments,
	});
	for (const id of plan.unrouted) {
		const q = model.quests.get(id);
		warn(`quest ${id} "${q.title}" was a candidate but never became available (prerequisite or level)`);
	}
	return { text, plan, model, warnings, report: { routed: plan.routed, excluded: model.excluded, unrouted: plan.unrouted, final } };
}

module.exports = { draft, loadData };
