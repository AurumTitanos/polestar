'use strict';
// Build the native dashboard's terrain texture index from the same cached
// WDT MAID records as Planner. FileDataIDs only: no client artwork is copied.
// Run after `planner art`; --check validates the checked-in result offline.

const fs = require('node:fs');
const path = require('node:path');
const { ROOT, SOURCES } = require('./lib/paths');
const { parseCsv } = require('./lib/data/csv');
const { readMaid } = require('./lib/planner/art/wdt');
const { checkBuild } = require('./lib/planner/art/casc');

const ART = path.join(ROOT, 'data/local/planner/art/index.json');
const OUTPUT = path.join(ROOT, 'addon/Polestar/UI/LiveTerrain.lua');

function integer(n, label, lo, hi = Number.MAX_SAFE_INTEGER) {
	if (!Number.isSafeInteger(n) || n < lo || n > hi) throw new Error(`${label}: invalid integer ${n}`);
	return n;
}

function quoted(value) {
	// Lua accepts these escapes; do not allow JSON-only control escapes.
	if (typeof value !== 'string' || /[\x00-\x1f]/.test(value)) throw new Error('Invalid terrain metadata text');
	return JSON.stringify(value);
}

function buildIndex({ indexPath = ART, sourcesDir = SOURCES } = {}) {
	const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
	if (index.schema !== 1) throw new Error(`Unsupported Planner art schema: ${index.schema}`);
	const build = checkBuild(index.build, 'Planner art');
	const product = index.product;
	if (typeof product !== 'string' || !/^[a-z0-9_]+$/.test(product)) throw new Error('Invalid Planner product');
	const mapFile = path.join(sourcesDir, 'wago', build, 'Map.csv');
	const rows = new Map(parseCsv(fs.readFileSync(mapFile, 'utf8')).map((r) => [Number(r.ID), r]));
	const continents = [];
	for (const [key, art] of Object.entries(index.continents || {}).sort(([a], [b]) => Number(a) - Number(b))) {
		const id = integer(Number(key), 'Continent ID', 0);
		const row = rows.get(id);
		if (!row) throw new Error(`Continent ${id} is missing from ${mapFile}`);
		const wdt = integer(Number(row.WdtFileDataID), `Continent ${id} WDT`, 1);
		const file = path.join(sourcesDir, 'casc', product, build, `${wdt}.blp`);
		const tiles = readMaid(fs.readFileSync(file));
		if (!tiles.length) throw new Error(`Continent ${id} has no minimap textures`);
		const expected = new Set((art.levels?.[0] || []).map(([col, r]) => `${col}_${r}`));
		if (expected.size !== tiles.length || tiles.some((t) => !expected.has(`${t.col}_${t.row}`))) {
			throw new Error(`Continent ${id} WDT tiles differ from Planner art; finish rebuilding planner art first`);
		}
		const bounds = {
			minCol: Math.min(...tiles.map((t) => t.col)), maxCol: Math.max(...tiles.map((t) => t.col)),
			minRow: Math.min(...tiles.map((t) => t.row)), maxRow: Math.max(...tiles.map((t) => t.row)),
		};
		for (const [name, value] of Object.entries(bounds)) {
			if (art.bounds?.[name] !== value) throw new Error(`Continent ${id} ${name} differs from Planner art`);
		}
		const sea = art.sea || index.tile?.sea;
		if (!Array.isArray(sea) || sea.length !== 3) throw new Error(`Continent ${id} sea color is missing`);
		sea.forEach((v) => integer(v, 'Sea RGB byte', 0, 255));
		continents.push({ id, name: row.MapName_lang, wdt, bounds, sea, tiles });
	}
	if (!continents.length) throw new Error('Planner art has no continents');
	return { build, product, continents };
}

function renderLua(data) {
	const out = [
		'-- Generated by `node tools/build-live-terrain.js`; do not edit.',
		'-- The same native minimap terrain textures used by Polestar Planner.',
		'-- FileDataIDs only: artwork stays in the player\'s client. No external bridge.',
		'-- Source: cached Map.csv and each WDT MAID, verified against Planner art.',
		'-- tiles are { column, row, FileDataID }; sea is RGB bytes (0..255).',
		'-- Plane coordinates: X=-worldY, Y=-worldX; tile top-left=(col-32,row-32)*adt.',
		'',
		'local ADDON, ns = ...',
		'ns.LiveTerrain = {',
		`\tbuild = ${quoted(data.build)},`,
		`\tproduct = ${quoted(data.product)},`,
		'\tadt = 1600 / 3,',
		'\tcontinents = {',
	];
	for (const c of data.continents) {
		const b = c.bounds;
		out.push(`\t\t[${c.id}] = {`, `\t\t\tname = ${quoted(c.name)},`, `\t\t\twdt = ${c.wdt},`,
			`\t\t\tbounds = { minCol = ${b.minCol}, maxCol = ${b.maxCol}, minRow = ${b.minRow}, maxRow = ${b.maxRow} },`,
			`\t\t\tsea = { ${c.sea.join(', ')} },`, '\t\t\ttiles = {');
		for (const t of c.tiles) out.push(`\t\t\t\t{ ${t.col}, ${t.row}, ${t.fdid} },`);
		out.push('\t\t\t},', '\t\t},');
	}
	out.push('\t},', '}', '');
	return out.join('\n');
}

function main(args = process.argv.slice(2)) {
	if (args.some((a) => a !== '--check')) throw new Error('Usage: node tools/build-live-terrain.js [--check]');
	const data = buildIndex();
	const lua = renderLua(data);
	if (args.includes('--check')) {
		if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') !== lua) {
			throw new Error('LiveTerrain.lua is stale; run node tools/build-live-terrain.js');
		}
	} else fs.writeFileSync(OUTPUT, lua, 'utf8');
	const count = data.continents.reduce((n, c) => n + c.tiles.length, 0);
	console.log(`${args.includes('--check') ? 'Verified' : 'Generated'} ${count} native terrain IDs across ${data.continents.length} continents, build ${data.build}`);
}

if (require.main === module) {
	try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { buildIndex, renderLua };
